# 「해외증권거래소등에신고한사업보고서등의국내신고」 트랩.
# 보고서명에 "사업보고서" 가 들어 있지만 사업보고서가 아니다 — NYSE 상장 3사
# (KB금융·신한지주·우리금융)의 Form 20-F 국내신고로, 본문 27자 + 표 1개짜리
# 4.6 KB 껍데기다. 전 기간 70건, 2024~2026 접수 11건. 사업연도 표기 (YYYY.MM) 가
# 없다는 점으로 구별한다 — 그래서 아래 정규식이 선택적 필터가 아니라 필수 조건이다.
_ANNUAL_FY_RE = None   # is_annual_4cha 안에서 지연 컴파일


def annual_fy_4cha(report_nm):
    """'사업보고서 (2025.12)' → '2025'. 4차 대상이 아니면 ''."""
    import re
    global _ANNUAL_FY_RE
    if _ANNUAL_FY_RE is None:
        _ANNUAL_FY_RE = re.compile(r"\((\d{4})\.\d{2}\)")
    nm = report_nm or ""
    if "사업보고서" not in nm:
        return ""
    if "반기보고서" in nm or "분기보고서" in nm:
        return ""
    m = _ANNUAL_FY_RE.search(nm)
    if not m:
        return ""          # ← 20-F 국내신고가 여기서 걸러진다
    fy = m.group(1)
    return fy if fy in ANNUAL_FY_4CHA else ""


def is_meeting_notice_4cha(report_nm, rcept_dt):
    """주주총회소집공고(2024~2026 접수)인가. 본문만 받는다(웹 첨부는 사용자 결정으로 제외)."""
    return ("주주총회소집공고" in (report_nm or "")
            and (rcept_dt or "")[:4] in MEETING_NOTICE_YEARS_4CHA)


def is_4cha_doc(report_nm, rcept_dt=""):
    """4차 배치 문서인가. emit 의 좁은 규칙과 handoff 의 배치 라우팅이 같은 함수를 쓴다."""
    return bool(annual_fy_4cha(report_nm)) or is_meeting_notice_4cha(report_nm, rcept_dt)


