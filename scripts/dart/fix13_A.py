class Doc:
    def __init__(self, key, path, md=True):
        self.key, self.path, self.md = key, path, md
        raw = open(pre_path(path), "rb").read()
        self.bom = raw.startswith(b"\xef\xbb\xbf")
        self.text0 = raw.decode("utf-8-sig")
        self.lines = self.text0.split("\n")
        self.code, self.fixed = set(), set()
        self.ins = {}
        incode = on = False
        for i, ln in enumerate(self.lines):
            if md and ln.startswith("```"):
                self.code.add(i)
                incode = not incode
                continue
            if md and (incode or ln.startswith(">")):
                self.code.add(i)
            if md and ln.startswith("### 고친 곳"):
                on = True
                continue
            if on and (ln.startswith("### ") or ln.startswith("## ")):
                on = False
            if on:
                self.fixed.add(i)

    def log(self, i, before, after, rule, why):
        LOG.append(dict(파일=self.path, 줄_기준사본=i + 1, 전=before, 후=after, 규칙=rule, 이유=why))

    def sub(self, old, new, rule, why, count=1, pred=None, skip_fixed=True):
        hits = [i for i, ln in enumerate(self.lines) if i not in self.code and old in ln
                and (not skip_fixed or i not in self.fixed) and (pred is None or pred(i, ln))]
        n = sum(self.lines[i].count(old) for i in hits)
        if n != count:
            raise SystemExit(f"[fix13_A {self.key} {os.path.basename(self.path)}] 「{old[:80]}」 {n}번 나옴(기대 {count}) — {why}")
        for i in hits:
            b = self.lines[i]
            a = b.replace(old, new)
            self.lines[i] = a
            self.log(i, b, a, rule, why)

    def idx(self, pred, what):
        hits = [i for i, ln in enumerate(self.lines) if i not in self.code and pred(i, ln)]
        if len(hits) != 1:
            raise SystemExit(f"[fix13_A {self.key}] {what}: {len(hits)}줄(기대 1)")
        return hits[0]

    def set_line(self, i, new, rule, why):
        b = self.lines[i]
        if b != new:
            self.lines[i] = new
            self.log(i, b, new, rule, why)

    def insert_after(self, i, new_lines, rule, why):
        self.ins.setdefault(i, []).extend(new_lines)
        LOG.append(dict(파일=self.path, 줄_기준사본=f"{i + 1} 뒤에 끼움", 전="-", 후=list(new_lines), 규칙=rule, 이유=why))

    def section(self, head_prefix):
        """머리 줄이 head_prefix 로 시작하는 절의 (시작, 끝) 줄 번호(0부터, 끝은 다음 같은 급 머리 전)."""
        s = self.idx(lambda i, ln: ln.startswith(head_prefix), f"절 머리 「{head_prefix}」")
        lvl = len(head_prefix) - len(head_prefix.lstrip("#"))
        e = len(self.lines)
        for j in range(s + 1, len(self.lines)):
            ln = self.lines[j]
            m = re.match(r"^(#+) ", ln)
            if m and len(m.group(1)) <= lvl and j not in self.code:
                e = j
                break
        return s, e

    def final(self):
        out = []
        for i, ln in enumerate(self.lines):
            out.append(ln)
            out.extend(self.ins.get(i, []))
        return out

    def write(self):
        s = "\n".join(self.final())
        data = s.encode("utf-8")
        if self.bom:
            data = b"\xef\xbb\xbf" + data
        open(self.path, "wb").write(data)


