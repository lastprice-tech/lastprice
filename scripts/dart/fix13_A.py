def check():
    probs = []
    if not os.path.exists(LOGF):
        print("fix_log.json 없음")
        return 1
    log = json.load(open(LOGF, encoding="utf-8"))["보정"]
    cur = {}
    for p in list(MD.values()) + list(TOC.values()):
        cur[p] = open(p, "rb").read().decode("utf-8-sig").split("\n")   # 줄 끝(\r\n) 그대로
    last = {}
    for x in log:   # 같은 줄을 여러 번 고쳤으면 마지막 「후」만 지금 파일에 있어야 함
        last[(x["파일"], str(x["줄_기준사본"]))] = x
    for x in last.values():
        after = x["후"] if isinstance(x["후"], list) else [x["후"]]
        for a in after:
            if a not in cur[x["파일"]]:
                probs.append(f"{os.path.basename(x['파일'])}: 「후」 줄이 지금 파일에 없음 — {a[:70]}")
    for c, p in MD.items():
        pre = open(pre_path(p), encoding="utf-8").read().split("\n")

        def code_lines(L):
            out, incode = [], False
            for ln in L:
                if ln.startswith("```"):
                    incode = not incode
                    out.append(ln)
                    continue
                if incode or ln.startswith(">"):
                    out.append(ln)
            return out
        if code_lines(pre) != code_lines(cur[p]):
            probs.append(f"{os.path.basename(p)}: 원문 인용(코드 블록) 줄이 기준 사본과 다름")
        probs += state_match(c, cur[p])
    rows = list(csv.DictReader(open(STATE_CSV, encoding="utf-8-sig")))
    if len(rows) != len(CO) * len(ARTS):
        probs.append(f"상태 CSV {len(rows)}행(기대 {len(CO) * len(ARTS)})")
    for r in rows:
        c = next(k for k, v in CO.items() if v == r["회사"])
        if r["상태"] != STATUS[c][r["모범규준_조"]][0]:
            probs.append(f"상태 CSV {r['회사']} {r['모범규준_조']}조 상태가 스크립트와 다름")
        if not (r["상태"] == "받은 글" or r["상태"].startswith("일부(") or r["상태"].startswith("추출 범위에 없음")):
            probs.append(f"상태 CSV {r['회사']} {r['모범규준_조']}조 상태가 R1 세 단계가 아님")
        if r["상태"] != "받은 글" and (r["찾은_방법"] in ("", "-") or r["빠진_핵심"] in ("", "-")):
            probs.append(f"상태 CSV {r['회사']} {r['모범규준_조']}조 빠진 핵심·찾은 방법 없음")
    print(f"fix13_A check: fix_log {len(log)}곳, 상태 CSV {len(rows)}행 — 문제 {len(probs)}건")
    for x in probs[:40]:
        print("  ✗", x)
    return 1 if probs else 0


