def zero_rows(d, rows):
    """0장 요약 표 — rows: {첫 칸: (상태, 인용 칸 앞에 붙일 글, [(인용 칸 안 전, 후)], 기본 찾은 방법 조)}."""
    s, e = d.section("## 0. ")
    pidx = 2 if d.key in ("M", "K") else 3
    for first, (st, pre, subs, art) in rows.items():
        i = d.idx(lambda j, ln: s < j < e and ln.startswith(f"| {first} | "), f"0장 「{first}」 행")
        cells = [x.strip() for x in d.lines[i].strip().strip("|").split("|")]
        old_p = cells[pidx]
        tr = re.search(r"\((찾은 (?:방법|범위))[^()]*\)", old_p)
        cite = cells[-1]
        for o, n in subs:
            if cite.count(o) != 1:
                raise SystemExit(f"[fix13_A {d.key}] 0장 「{first}」 인용 칸 「{o[:40]}」 {cite.count(o)}번")
            cite = cite.replace(o, n)
        cite = cite.replace("가까운 글:", "가까운 글(판단):")
        if pre:
            cite = pre + cite
        if tr and tr.group(0) not in cite:
            cite = cite + " " + tr.group(0)
        cells[pidx] = st
        cells[-1] = cite
        line = "| " + " | ".join(cells) + " |"
        if "추출 범위에 없음" in line and not TRAIL_RE.search(line):
            cells[-1] = cite + " " + dtrail(art)
            line = "| " + " | ".join(cells) + " |"
        d.set_line(i, line, "R1", f"0장 「{first}」 행 판정 칸을 R1 상태로(찾은 방법은 인용 칸)")


