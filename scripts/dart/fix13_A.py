def parse_quotes(lines, fname):
    out = {}
    cur = None
    for i, ln in enumerate(lines):
        m = QID_RE.match(ln)
        if m:
            cur = m.group(1)
            out[cur] = dict(line=i + 1, cite=None, tag=None)
        elif cur and ln.startswith("- 인용:") and out[cur]["cite"] is None:
            out[cur]["cite"] = ln
        elif cur and ln.startswith("- 이 글이 닿는 모범규준 조") and out[cur]["tag"] is None:
            out[cur]["tag"] = ln
        elif ln.startswith("## ") or ln.startswith("### "):
            cur = None
    return out


def cite_short(qid, q, fname):
    parts = [x.strip() for x in q["cite"][len("- 인용: ["):].rstrip().rstrip("]").split(" · ")]
    ref = next((x for x in parts if x.startswith("접수번호 ")), None) or next((x for x in parts if x.startswith("http")), "")
    page = next((x for x in parts if x.startswith("p.") or x.startswith("제")), "")
    return f"[{qid}] {fname}:{q['line']} · {parts[0]} · {ref} · {page}"


def sec6_rows(lines, key):
    s = next(i for i, ln in enumerate(lines) if ln.startswith("## 6. "))
    out = []
    for ln in lines[s:]:
        if ln.startswith("## 7"):
            break
        if ln.startswith(f"| {key} | `"):
            a, b = ln.index("`") + 1, ln.rindex("` | ")
            rest = [x.strip() for x in ln[b + 4:].strip().strip("|").split("|")]
            out.append([key, ln[a:b]] + rest)
    return out


def refute_line(lines, key):
    v = next(i for i, ln in enumerate(lines) if ln.startswith("## 검증 기록"))
    for ln in lines[v:]:
        if ln.startswith(f"- 「{key}」"):
            return ln
    return ""


