# ───────────────────────────── 상태 일치 대조 ─────────────────────────────
def state_match(c, lines):
    """md 0장·3장·7장의 조별 상태 글이 STATUS(=상태 CSV)와 같은지 → 문제 목록."""
    bad = []
    pidx = 2 if c in ("M", "K") else 3
    s0 = next(i for i, ln in enumerate(lines) if ln.startswith("## 0. "))
    e0 = next(i for i in range(s0 + 1, len(lines)) if lines[i].startswith("## 1"))
    zero = {}
    for ln in lines[s0:e0]:
        if ln.startswith("| ") and "|---" not in ln:
            cells = [x.strip() for x in ln.strip().strip("|").split("|")]
            zero[cells[0]] = cells[pidx]
    s7 = next(i for i, ln in enumerate(lines) if ln.startswith("## 7. "))
    seven = {}
    for ln in lines[s7:]:
        if ln.startswith("## ") and not ln.startswith("## 7. "):
            break
        if ln.startswith("| 9-4 "):
            cells = [x.strip() for x in ln.strip().strip("|").split("|")]
            seven[cells[0]] = cells[4]
    text = "\n".join(lines)
    for a in ARTS:
        S = STATUS[c][a][0]
        z = zero.get("4·5" if a in ("4", "5") else a)
        if z != S:
            bad.append(f"{CO[c]} 0장 {a}조 판정 「{z}」 ≠ CSV 「{S}」")
        item = {"4": "9-4 3.", "5": "9-4 3.", "21": "9-4 2. 21·22·24", "22": "9-4 2. 21·22·24", "24": "9-4 2. 21·22·24"}.get(a, f"9-4 2. {a}")
        if a in ("21", "22", "24") and f"9-4 2. {a}" in seven:
            item = f"9-4 2. {a}"
        if seven.get(item) != S:
            bad.append(f"{CO[c]} 7장 「{item}」 상태 「{seven.get(item)}」 ≠ CSV {a}조 「{S}」")
        if f"**{S}**" not in text:
            bad.append(f"{CO[c]} 3장 판정에 {a}조 상태 「{S}」 굵은 글 없음")
        if "찾은 글" in (z or "") or "찾은 글" in (seven.get(item) or ""):
            bad.append(f"{CO[c]} {a}조 상태에 찾은 글 낱말")
    return bad


