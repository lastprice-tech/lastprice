BEFORE0 = {}


def fix():
    ensure_pre()
    LOG.clear()
    docs = {}
    for c in CO:
        d = Doc(c, MD[c])
        # 0장 판정 칸(전) 기록
        s, e = d.section("## 0. ")
        pidx = 2 if c in ("M", "K") else 3
        BEFORE0[c] = {}
        for ln in d.lines[s:e]:
            if ln.startswith("| ") and "|---" not in ln:
                cells = [x.strip() for x in ln.strip().strip("|").split("|")]
                BEFORE0[c][cells[0]] = cells[pidx]
        nq = sum(1 for ln in d.lines if QID_RE.match(ln))
        # 표지만 있던 묶음의 인용 번호
        only = []
        cur = None
        for ln in d.lines:
            m = QID_RE.match(ln)
