CITE_RE = re.compile(r"^\[(?P<doc>.+?) · (?P<loc>접수번호 \d{14}|https?://\S+) · 쪽 (?P<pages>p\.\d+(?:–p\.\d+)?) · ")


def build_rows(co, lines):
    titles = jo_titles()
    path = MD[co]
    arts = quote_arts(lines)
    head_ln, cite = {}, {}
    cur = None
    for i, ln in enumerate(lines):
        q = qid_of_head(ln.t)
        if q:
            cur = q
            head_ln[q] = i + 1
            continue
        if ln.t.startswith("## "):
            cur = None
        if cur and cur not in cite and ln.t.startswith("[") and " · 쪽 p." in ln.t:
            cite[cur] = CITE_RE.match(ln.t)
    order = [q for q in head_ln]
    # 3장 찾은 범위·검증 반박, 5장 정규식
    sub3, cur3, sec = {}, None, None
    for ln in lines:
        if ln.t.startswith("## "):
            sec = ln.t
            cur3 = None
        if sec and sec.startswith("## 3.") and ln.t.startswith("### "):
            cur3 = tuple(art_numbers(ln.t[4:].split(" — ")[0]))
            sub3[cur3] = []
        elif cur3 and (ln.t.startswith("- 찾은 범위:") or ln.t.startswith("- 검증 반박(")):
            sub3[cur3].append(ln.t[2:])
    rx = {}
    sec = None
    for ln in lines:
        if ln.t.startswith("## "):
            sec = ln.t
        if sec and sec.startswith("## 5.") and ln.t.startswith("| ") and "`" in ln.t:
            cells = [c.strip() for c in ln.t.strip().strip("|").split("|")]
            rx.setdefault(cells[0], [])
            r = cells[-1]
            if r not in rx[cells[0]]:
                rx[cells[0]].append(r)
    # 검증 기록 반박 검색어 표(KB·신한: 「| 조 | 검색어(낱말) | 정규식 | …」) — 3장 찾은 범위 줄에 반박이 안 적힌 조(22·24)에 덧붙임
    ref = {}
    sec = None
    for ln in lines:
        if ln.t.startswith("## "):
            sec = ln.t
        if sec and sec.startswith("## 검증 기록") and ln.t.startswith("| ") and "`" in ln.t:
            cells = [c.strip() for c in ln.t.strip().strip("|").split("|")]
            if len(cells) == 4:
                ref.setdefault(cells[0], cells[1])
    rows = []
    for a in REQ_ARTS:
        stt, have, miss, bigo = STATUS[co][a]
        ev = []
        for q in order:
            if a in arts.get(q, set()):
                m = cite.get(q)
                ev.append(f"{q}({path}:{head_ln[q]} · {m.group('doc')} · {m.group('loc')} · {m.group('pages')})" if m else f"{q}({path}:{head_ln[q]})")
        key = next(k for k in sub3 if a in k)
        lab = "4·5조" if a in (4, 5) else f"{a}조"
        labs = [lab] + (["21·22·24 연결"] if a in (21, 22, 24) else [])
        rxs = " · ".join(f"5장 정규식({l}): {' / '.join(rx.get(l, ['-']))}" for l in labs)
        how = " / ".join(sub3[key]) + " · " + rxs
        if "반박" not in how:
            rl = "21·22·24" if a in (21, 22, 24) else ("4·5" if a in (4, 5) else str(a))
            if rl in ref:
                how += f" · 반박 검색(검증 기록 표 ‘{rl}’, 같은 세 문서·대조판과 FY2023·FY2024 사업보고서): 검색어 {ref[rl]}"
        rows.append({"회사": CO[co], "모범규준_조": str(a), "조_제목": titles[a], "지시서_핵심": CORE[a], "상태": stt,
                     "있는_핵심": have, "빠진_핵심": miss, "근거": "; ".join(ev) or "-", "찾은_방법": how, "비고": bigo})
    return rows


COLS = ["회사", "모범규준_조", "조_제목", "지시서_핵심", "상태", "있는_핵심", "빠진_핵심", "근거", "찾은_방법", "비고"]


def write_state(allrows):
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=COLS, lineterminator="\r\n")
    w.writeheader()
    for r in allrows:
        w.writerow(r)
    open(STATE_CSV, "w", encoding="utf-8-sig", newline="").write(buf.getvalue())


