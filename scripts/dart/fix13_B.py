def sub_count(path, lines, old, new, exp, rule, why, pred=None):
    n = 0
    for ln, sec in zip(lines, sec_of(lines)):
        if ln.q or old not in ln.t or (pred and not pred(ln, sec)):
            continue
        k = ln.t.count(old)
        before = ln.t
        ln.t = ln.t.replace(old, new)
        n += k
        log(path, ln, before, ln.t, rule, why)
    if n != exp:
        die(f"{path}: 「{old[:60]}」 {n}번(예상 {exp})")
    return n


def qid_of_head(t):
    m = re.match(r"^### ([KSHW]-\d+b?) ", t)
    return m.group(1) if m else None


def quote_arts(lines):
    arts, cur = {}, None
    for ln in lines:
        q = qid_of_head(ln.t)
        if q:
            cur = q
        elif ln.t.startswith("## "):
            cur = None
        if cur and ln.t.startswith("모범규준 조:"):
            arts[cur] = set(art_numbers(ln.t[len("모범규준 조:"):]))
    return arts


