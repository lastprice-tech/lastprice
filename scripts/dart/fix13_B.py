class Ln:
    __slots__ = ("t", "pre", "q")

    def __init__(self, t, pre=None, q=False):
        self.t, self.pre, self.q = t, pre, q


LOGS = []


def log(path, obj, before, after, rule, why):
    LOGS.append(dict(file=path, obj=obj, before=before, after=after, rule=rule, why=why))


def die(msg):
    print("멈춤:", msg)
    sys.exit(2)


def ensure_pre(path):
    p = os.path.join(PRE, path)
    if not os.path.exists(p):
        os.makedirs(os.path.dirname(p), exist_ok=True)
        data = subprocess.run(["git", "show", f"{BASE}:{path}"], capture_output=True, check=True).stdout
        open(p, "wb").write(data)
    return open(p, encoding="utf-8", newline="").read()      # 줄 끝(CSV 의 \r\n)을 그대로


def load_lines(text):
    out, inc = [], False
    for i, t in enumerate(text.split("\n")):
        if t.startswith("```"):
            out.append(Ln(t, i + 1, True))
            inc = not inc
            continue
        out.append(Ln(t, i + 1, inc or t.startswith(">")))
    return out


def quote_lines(text):
    """원문 인용 줄(코드 블록 안·「>」 줄·울타리 줄) 차례."""
    return [ln.t for ln in load_lines(text) if ln.q]


def sec_of(lines):
    cur, out = None, []
    for ln in lines:
        if ln.t.startswith("## "):
            cur = ln.t
        out.append(cur)
    return out


def art_numbers(s):
    out = []
    for g in re.finditer(r"(?<![\d제])(\d{1,2}(?:·\d{1,2})*)조", s):
        out += [int(x) for x in g.group(1).split("·")]
    return sorted(set(out))


