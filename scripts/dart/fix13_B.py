def r2(co, path, lines):
    heads, tagged, cur = [], set(), None
    rep = []
    for ln in lines:
        q = qid_of_head(ln.t)
        if q:
            cur = q
            heads.append(q)
            continue
        if ln.t.startswith("## "):
            cur = None
        if ln.q or not ln.t.startswith("모범규준 조:"):
            continue
        if cur:
            tagged.add(cur)
        body = ln.t[len("모범규준 조:"):]
        b2, removed, toc = conv_tag(body)
        if b2 != body:
            before = ln.t
            ln.t = "모범규준 조:" + b2
            parts = []
            if removed:
                parts.append("지시서 조 " + "·".join(f"{x}조" for x in sorted(set(removed))) + " 의 (판단) 뗌(지시서 조 번호는 그대로, 대응 판단은 줄 끝 note)")
            if toc:
                parts.append("조문 목차 표지 → 9-4 조문 대조(대조표 A~C)")
            log(path, ln, before, ln.t, "R2", "; ".join(parts))
            rep.append((cur, before, ln.t))
    miss = [q for q in heads if q not in tagged]
    if miss:
        die(f"{path}: 「모범규준 조:」 줄 없는 묶음 {miss}")
    return rep, len(heads)


