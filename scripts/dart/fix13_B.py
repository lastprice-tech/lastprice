    for ln in lines:
        if not ln.q and ln.t.startswith(HDR_OLD):
            b = ln.t
            ln.t = HDR_NEW + ln.t[len(HDR_OLD):]
            stat["header"] += 1
            log(path, ln, b, ln.t, "R5", "머리 수집일 — 1차 정리 시각(UTC 2026-10-07 14:36~16:44)은 KST 로 10-07~08, 경영공시 원본 수집은 UTC 날짜(KST 10-01)")
