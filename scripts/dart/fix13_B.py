def fix():
    LOGS.clear()
    allrows, summary = [], {}
    for co in ("K", "S", "H", "W"):
        path = MD[co]
        pre_text = ensure_pre(path)
        lines = load_lines(pre_text)
        r5s = r5(co, path, lines)
        r5s["blocks"] = sum(1 for ln in lines if ln.q and ln.t.startswith("```")) // 2
        tagrep, nblocks = r2(co, path, lines)
        r3done = []
        for old, new, n, why in R3[co]:
            sub_count(path, lines, old, new, n, "R3", why)
            r3done.append((old, new, why, n))
        wn = 0
        for old, new in R1_WORDS:
            n = sum(ln.t.count(old) for ln in lines if not ln.q)
            if n:
                sub_count(path, lines, old, new, n, "R1", "낱말 — 가까운 글 안내 「찾은 것」 → 가까운 글(판단)")
            wn += n
        if wn != R1_WORDS_N[co]:
            die(f"{path}: 「찾은 것」 {wn}곳(예상 {R1_WORDS_N[co]})")
        r1_tables(co, path, lines)
        heads(co, path, lines)
        sec = section(co, tagrep, nblocks, r5s, r3done, wn, VERIFY[co])
        while lines and lines[-1].t == "" and not lines[-1].q:     # 원본 끝 빈 줄 → 소절 뒤로
            lines.pop()
        for t in sec + [""]:
            nl = Ln(t)
            lines.append(nl)
            if t:
                log(path, nl, "", t, "R1-R5", "검증 기록 끝 「### 정합성 보정(2026-10-08)」 소절 — 바꾼 것(전·후)")
        text = "\n".join(ln.t for ln in lines)
        if not text.endswith("\n"):
            text += "\n"
        open(path, "w", encoding="utf-8").write(text)
        # 조문 목차 CSV
        ttext = ensure_pre(TOC[co])
        tl = ttext.split("\n")
        for old, new, n, why in R3_TOC[co]:
            k = 0
            for i, t in enumerate(tl):
                if old in t:
                    b = t
                    tl[i] = t.replace(old, new)
                    k += t.count(old)
                    LOGS.append(dict(file=TOC[co], obj=None, line=i + 1, before=b, after=tl[i], rule="R3", why=why + " (md 1-2 표와 같은 칸)"))
            if k != n:
                die(f"{TOC[co]}: 「{old}」 {k}번(예상 {n})")
        open(TOC[co], "w", encoding="utf-8", newline="").write("\n".join(tl))
        allrows += build_rows(co, [Ln(t) for t in text.split("\n")])
        summary[co] = dict(r5=r5s, tags=len(tagrep), r3=sum(n for *_, n in r3done), words=wn)
        # 로그 줄 번호(보정 뒤)
        idx = {id(ln): i + 1 for i, ln in enumerate(lines)}
        for e in LOGS:
            if e.get("obj") is not None and e["file"] == path:
                e["line"] = idx[id(e["obj"])]
                e["pre_line"] = e["obj"].pre
    write_state(allrows)
    # 같은 줄을 여러 규칙이 고친 것은 한 항목으로(전 = 기준 사본 줄, 후 = 지금 줄)
    out, pos = [], {}
    for e in LOGS:
        key = (e["file"], id(e["obj"])) if e.get("obj") is not None else (e["file"], e["line"])
        if key in pos:
            d = out[pos[key]]
            d["after"] = e["after"]
            if e["rule"] not in d["rule"].split("+"):
                d["rule"] += "+" + e["rule"]
            if e["why"] not in d["why"]:
                d["why"] += " | " + e["why"]
            continue
        pos[key] = len(out)
        out.append({k: v for k, v in e.items() if k != "obj"})
    for d in out:
        d.setdefault("pre_line", None)
    json.dump(dict(base=BASE, rules="FIXRULES13 R1~R5", note="line = 보정 뒤 줄 번호, pre_line = 기준 사본(496ddc4) 줄 번호(새로 끼운 줄은 null)",
                   summary=summary, edits=out), open(LOG, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"보정: 고친 곳 {len(out)}개 → {LOG}; 상태 CSV {len(allrows)}행 → {STATE_CSV}")
    for co, s in summary.items():
        print(f"  {CO[co]}: 태그 줄 {s['tags']}, R3 {s['r3']}, 낱말 {s['words']}, R5 출처 줄 {s['r5']['cite_first']}+{s['r5']['cite_added']}·경영공시 {s['r5']['md_fetched']}·라벨 줄 {s['r5']['labels']}")


