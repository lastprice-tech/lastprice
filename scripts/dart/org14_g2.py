def comm_staff_search(docs, name):
    """critic14_2 — 위원회 행 직원 인원 찾기: 본 사업보고서·연차보고서(본·추가공시)·경영공시 텍스트에서 위원회 이름(공백·가운뎃점 꼴 무시)과
    「N명」이 같은 줄에 있는 줄 수와, 그중 직원 낱말(STAFF_WORDS)이 함께 있는 줄 수."""
    def nz(s):
        return ws(s).replace("ㆍ", "·").replace("・", "·").replace("‧", "·").replace("∙", "·")
    key = nz(name)
    n_hit = n_staff = 0
    for dk in ("biz", "annual", "annual_add", "mgmt"):
        for l in docs[dk].lines:
            if key in nz(l) and re.search(r"\d+\s*명", l):
                n_hit += 1
                if any(w in l for w in STAFF_WORDS):
                    n_staff += 1
    return n_hit, n_staff


