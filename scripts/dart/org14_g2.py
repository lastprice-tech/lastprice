_XML = {}


def xml_sections(rcept):
    if rcept not in _XML:
        with open(P("dart_out/raw/document", rcept + ".zip"), "rb") as f:
            body = f.read()
        info = docparse.read_zip(body, rcept)
        secs, err = docparse.parse_document(info["text"])
        if err:
            PROBLEMS.append(f"XML {rcept} 파서 경고: {err}")
        _XML[rcept] = secs
    return _XML[rcept]


def expand(rows):
    """rowspan/colspan 을 펼쳐 칸 글자 격자로."""
    grid, pending = [], {}
    for r in rows:
        out, cells, col = [], list(r), 0
        while cells or col in pending:
            if col in pending:
                t, rem = pending[col]
                out.append(t)
                if rem > 1:
                    pending[col] = (t, rem - 1)
                else:
                    del pending[col]
                col += 1
                continue
            c = cells.pop(0)
            rs = int(c.get("rowspan") or 1)
            cs = int(c.get("colspan") or 1)
            for _ in range(cs):
                out.append(c["text"])
                if rs > 1:
                    pending[col] = (c["text"], rs - 1)
                col += 1
        grid.append(out)
    return grid


def xml_section(rcept, title):
    for s in xml_sections(rcept):
        if s["title_raw"].strip() == title:
            return s
    raise SystemExit(f"XML {rcept} 장 없음: {title}")


def xml_tables(sec, head):
    out = []
    for t in sec["tables"]:
        if not t["rows"]:
            continue
        g = expand(t["rows"])
        if [ws(x) for x in g[0][: len(head)]] == [ws(x) for x in head]:
            out.append(g)
    return out


