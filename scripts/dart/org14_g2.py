# ───────────────────────── 대응(임원 ↔ 조직 단위) ─────────────────────────
BOUND_L = r"(?<![가-힣A-Za-z0-9ㆍ·])"
BOUND_R = r"(?=$|[^가-힣A-Za-z0-9ㆍ·]|장|소속)"


def name_rx(name):
    parts = [re.escape(p) for p in name.split()]
    return re.compile(BOUND_L + r"\s*".join(parts) + BOUND_R)


def role_after(text, m):
    t = text[m.end():]
    mm = re.match(r"\s*(위원장|위원|의장)", t)
    if mm:
        return mm.group(1)
    mm = re.match(r"(장|소속)", t)
    if mm:
        return text[m.start():m.end()] + mm.group(1)
    return ""


def map_unit(co, unit, offs, extra_duty):
    """unit 이름이 담당업무(또는 직위·주8 원문)에 글자 그대로 있으면 이름 일치."""
    hits = []
    rx = name_rx(unit)
    for o in offs:
        srcs = [("담당업무", o["담당업무"])]
        if unit in ("대표이사 회장", "대표이사"):
            srcs.append(("직위", o["직위"]))
        if o["성명"] in extra_duty:
            srcs.append(extra_duty[o["성명"]])
        for fld, txt in srcs:
            m = rx.search(txt)
            if m:
                hits.append(dict(o=o, 방식="이름 일치", 근거=f"{fld} 「{txt}」", 역할=role_after(txt, m)))
                break
        else:
            # 띄어쓰기만 다른 경우
            for fld, txt in srcs:
                if ws(unit) and re.search(BOUND_L + re.escape(ws(unit)) + BOUND_R, ws(txt)) and not rx.search(txt):
                    hits.append(dict(o=o, 방식="(판단) 띄어쓰기만 다름", 근거=f"{fld} 「{txt}」 — 조직도 「{unit}」와 띄어쓰기만 다름", 역할=""))
                    break
    for nm, why in JUDGE[co].get(unit, []):
        for o in offs:
            if o["성명"] == nm and not any(h["o"] is o for h in hits):
                hits.append(dict(o=o, 방식="(판단)", 근거=f"담당업무 「{o['담당업무']}」 — {why}", 역할=""))
    return hits


