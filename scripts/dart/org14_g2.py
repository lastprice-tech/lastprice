def load_docs(co, meta):
    d = {}
    labels = {"biz": "사업보고서", "biz_amend": "[기재정정]사업보고서", "annual": "연차보고서", "annual_add": "연차보고서(추가공시)", "mgmt": "경영공시"}
    for k, m in meta.items():
        lab = m["문서"] if k in ("biz", "biz_amend") else f"{labels[k]} 「{m['문서']}」"
        ident = m["id"] if k in ("biz", "biz_amend") else m["url"]
        d[k] = TextDoc(m["file"], lab, ident, m["수집"])
    return d


