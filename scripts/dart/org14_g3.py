def build_quotes(co, docs):
    qs = {}
    for qid, dk, after, s, e, label, sec in QUOTE_SPECS[co]:
        d = docs[dk]
        a0 = d.line(after) if after else 0
        l1 = d.line(s, a0)
        l2 = l1 + int(e[1:]) if e.startswith("+") else d.line(e, l1)
        if l2 - l1 > 80:
            PROBLEMS.append(f"{co} {qid} 인용이 너무 김({l2 - l1}줄)")
        qs[qid] = dict(id=qid, doc=dk, l1=l1, l2=l2, label=label, sec=sec, lines=d.lines[l1:l2 + 1], src=d.src(l1, l2), short=d.short(l1, l2))
    return qs


