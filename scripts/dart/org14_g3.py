def nfix(s, cnt=None):
    s = "" if s is None else str(s)
    for a, b in OUT_FIX:
        n = s.count(a)
        if n:
            s = s.replace(a, b)
            if cnt is not None:
                cnt[a] = cnt.get(a, 0) + n
    return s


def md_fix(text, cnt):
    """md 에 OUT_FIX 를 쓴다 — 코드 블록·「>」 줄은 그대로, 7-2 「| 곳 | 고치기 전 | 고친 뒤 | 까닭 |」 표는 둘째·셋째 칸(지난 기록)을 그대로."""
    out, inb, ba = [], False, False
    for ln in text.split("\n"):
        if ln.startswith("```"):
            inb = not inb
            out.append(ln)
            continue
        if inb or ln.startswith(">"):
            out.append(ln)
            continue
        if ln.startswith("| 곳 | 고치기 전 | 고친 뒤 |"):
            ba = True
        elif not ln.startswith("|"):
            ba = False
        if ba and ln.startswith("| ") and ln.endswith(" |") and not ln.startswith("| 곳 |"):
            c = ln[2:-2].split(" | ")
            out.append("| " + " | ".join([nfix(c[0], cnt)] + c[1:3] + [nfix(x, cnt) for x in c[3:]]) + " |")
            continue
        out.append(nfix(ln, cnt))
    return "\n".join(out)


