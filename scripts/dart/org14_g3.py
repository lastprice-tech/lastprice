# ───────────────────────── 대응(임원 ↔ 조직 단위) ─────────────────────────
BOUND_L = r"(?<![가-힣A-Za-z0-9ㆍ·])"
BOUND_R = r"(?=$|[^가-힣A-Za-z0-9ㆍ·]|장|소속|겸)"


def name_rx(name):
    parts = [re.escape(p) for p in name.split()]
    return re.compile(BOUND_L + r"\s*".join(parts) + BOUND_R)


def role_after(text, m):
    t = text[m.end():]
    mm = re.match(r"\s*(위원장|위원|의장)", t)
    if mm:
        return mm.group(1)
    mm = re.match(r"(장|소속)", t)
    if mm:
        return text[m.start():m.end()] + mm.group(1)
    return ""


def duty_flat(o):
    return re.sub(r"\s*\n\s*", " ", o["담당업무"])


def career_hits(co, careers, o, unit):
    """임원약력(사람별 표)·임원 표 주요경력 칸에서 단위 이름 글자가 있는 줄."""
    hits = []
    for c in careers.get(o["성명"], []):
        if ws(unit) in ws(c["경력"]):
            hits.append(f"{c['기간']} {c['경력']}")
    if o.get("경력_xml") and ws(unit) in ws(o["경력_xml"]) and not hits:
        hits.append("임원 표 주요경력 칸에 「" + unit + "」 글자")
    return hits


def map_unit(co, unit, offs, careers):
    """unit 이름이 담당업무(대표이사는 직위 칸도)에 글자 그대로 있으면 이름 일치."""
    hits = []
    rx = name_rx(unit)
    for o in offs:
        txt = duty_flat(o)
        m = rx.search(txt)
        if m and m.group(0).strip() == unit:
            hits.append(dict(o=o, 방식="이름 일치", 근거=f"담당업무 「{txt}」", 역할=role_after(txt, m)))
            continue
        if m:
            hits.append(dict(o=o, 방식="(판단) 띄어쓰기만 다름", 근거=f"담당업무 「{txt}」 — 조직도(판독) 「{unit}」와 띄어쓰기만 다름", 역할=role_after(txt, m)))
            continue
        if ws(unit) and re.search(BOUND_L + re.escape(ws(unit)) + BOUND_R, ws(txt)):
            hits.append(dict(o=o, 방식="(판단) 띄어쓰기만 다름", 근거=f"담당업무 「{txt}」 — 조직도 「{unit}」와 띄어쓰기만 다름", 역할=""))
            continue
        if co in SIL_RULE and ws(unit).endswith("실") and len(ws(unit)) > 2:
            stem = ws(unit)[:-1]
            if re.search(BOUND_L + re.escape(stem) + r"(?=$|[^가-힣A-Za-z0-9ㆍ·])", ws(txt)):
                ch = career_hits(co, careers, o, unit)
                hits.append(dict(o=o, 방식="(판단) 「실」 글자만 빠짐", 근거=f"담당업무 「{txt}」 — 조직도 「{unit}」에서 「실」만 빠진 글자" +
                                 (f"; 임원약력·주요경력 원문에 「{unit}」: " + " / ".join(ch[:2]) if ch else ""), 역할=""))
    for nm, why in JUDGE[co].get(unit, []):
        for o in offs:
            if o["성명"] == nm and not any(h["o"] is o for h in hits):
                hits.append(dict(o=o, 방식="(판단)", 근거=f"담당업무 「{duty_flat(o)}」 — {why}", 역할=""))
    return hits


