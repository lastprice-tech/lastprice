def kis_careers(co, docs):
    """한국투자: 임원약력 표(■성명 다음 줄들) — 사람별 (기간, 경력) 과 텍스트 쪽·줄."""
    if co != "한국투자금융지주":
        return {}
    sec = xml_section(COS[co]["biz"], COS[co]["sec_officer"])
    t = next(t for t in sec["tables"] if t["rows"] and t["rows"][0][0]["text"].startswith("■"))
    d = docs["biz"]
    cur = d.line(r"^☞ 임원약력")
    res, person = {}, None
    for r in t["rows"]:
        tx = [c["text"] for c in r]
        if tx and tx[0].startswith("■"):
            person = tx[0].lstrip("■").strip()
            f = d.find(tx[0], cur)
            if f:
                cur = f[2] + 1
            continue
        if not person or not any(ws(x) for x in tx):
            continue
        f = d.find("".join(tx), cur)
        if f:
            cur = f[2] + 1
        res.setdefault(person, []).append(dict(기간=tx[0], 경력=tx[1] if len(tx) > 1 else "", 원문=f[0] if f else "",
                                               쪽=f"p.{d.page[f[1]]}" if f else "", 줄=f[1] + 1 if f else ""))
        if not f:
            PROBLEMS.append(f"{co} 임원약력 줄 텍스트에 없음: {person} {tx}")
    return res


