def to_kst(s):
    s = (s or "").strip()
    if not s:
        return ""
    s2 = re.sub(r"([+-]\d\d)(\d\d)$", r"\1:\2", s)
    try:
        d = datetime.datetime.fromisoformat(s2)
    except ValueError:
        return s
    if d.tzinfo is None:
        return s
    return d.astimezone(KST).strftime("%Y-%m-%d %H:%M KST")


# ───────────────────────── 텍스트 파일 ─────────────────────────
PAGE_RE = re.compile(r"^=== p\.(\d+) ===$")
FOOT_RE = re.compile(r"^전자공시시스템 dart\.fss\.or\.kr Page \d+$")


class TextDoc:
    """텍스트 파일 한 개. 줄(0부터)·쪽·공백 뺀 글자열(쪽 표지·DART 꼬리말 줄 제외)로 찾는다."""

    def __init__(self, path, label, ident, collected):
        self.path, self.label, self.ident, self.collected = path, label, ident, collected
        with open(P(path), encoding="utf-8") as f:
            self.lines = f.read().split("\n")
        self.page, self.skip = [], []
        S, pos = [], []
        p = 0
        for i, l in enumerate(self.lines):
            st = l.strip()
            m = PAGE_RE.match(st)
            if m:
                p = int(m.group(1))
            self.page.append(p)
            sk = bool(m) or bool(FOOT_RE.match(st))
            self.skip.append(sk)
            if sk:
                continue
            for j, ch in enumerate(l):
                if not ch.isspace():
                    S.append(ch)
                    pos.append((i, j))
        self.S = "".join(S)
        self.pos = pos
        self.line_off = {}
        for k, (i, _) in enumerate(pos):
            self.line_off.setdefault(i, k)

    def off_of_line(self, i):
        while i < len(self.lines):
            if i in self.line_off:
                return self.line_off[i]
            i += 1
        return len(self.S)

    def line(self, rx, after=0, must=True):
        r = re.compile(rx)
        for i in range(after, len(self.lines)):
            if r.search(self.lines[i]):
                return i
        if must:
            raise SystemExit(f"[{self.path}] 줄을 못 찾음: {rx} (after {after})")
        return None

    def _slice(self, k, n):
        a, b = self.pos[k], self.pos[k + n - 1]
        parts = []
        for i in range(a[0], b[0] + 1):
            if self.skip[i]:
                continue
            l = self.lines[i]
            s = a[1] if i == a[0] else 0
            e = b[1] + 1 if i == b[0] else len(l)
            parts.append(l[s:e])
        return "\n".join(x.strip() for x in parts), a[0], b[0]

    def find(self, text, lo=0, hi=None, off=None):
        """공백 무시로 text 를 찾아 (원문 조각, 첫 줄, 끝 줄, 끝 다음 글자 위치)."""
        n = ws(text)
        if not n:
            return None
        k = self.S.find(n, self.off_of_line(lo) if off is None else off)
        if k < 0:
            return None
        frag, l1, l2 = self._slice(k, len(n))
        if hi is not None and l1 > hi:
            return None
        return frag, l1, l2, k + len(n)

    def find_pieces(self, text, off, window=6000, maxpieces=4, minpiece=6):
        """칸 글자가 텍스트 파일에서 다른 줄(쪽 넘김·다음 제목)로 끊겨 있을 때: 앞에서부터 가장 긴 조각을 차례로 찾는다.
        돌려주는 것: (원문 조각들 '\n' 이음, 첫 줄, 끝 줄, 끝 다음 위치, 조각 수) 또는 None."""
        T = ws(text)
        if not T:
            return None
        pieces, cur, first, last = [], off, None, None
        while T:
            lo, hi = 0, len(T)
            best = None
            while lo < hi:  # T[:k] 가 [cur, cur+window) 안에 있는 가장 큰 k
                mid = (lo + hi + 1) // 2
                k = self.S.find(T[:mid], cur, cur + window + mid)
                if k >= 0:
                    lo, best = mid, k
                else:
                    hi = mid - 1
            if not lo or best is None or (lo < minpiece and lo < len(T)):
                return None
            frag, l1, l2 = self._slice(best, lo)
            pieces.append(frag)
            first = l1 if first is None else first
            last = l2
            cur = best + lo
            T = T[lo:]
            if len(pieces) > maxpieces:
                return None
        return "\n".join(pieces), first, last, cur, len(pieces)

    def pages(self, l1, l2):
        p1, p2 = self.page[l1], self.page[l2]
        return f"p.{p1}" if p1 == p2 else f"p.{p1}~{p2}"

    def src(self, l1, l2):
        return f"{self.label} · {self.ident} · {self.pages(l1, l2)} · 줄 {l1 + 1}–{l2 + 1} · {self.path} · 원본 수집 {self.collected}"

    def short(self, l1, l2):
        return f"{self.label} · {self.ident} · {self.pages(l1, l2)} · 줄 {l1 + 1}–{l2 + 1}"


