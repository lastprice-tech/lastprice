def find_cells(co, d, head_line, cells, label):
    """표 머리 줄 다음부터 칸을 차례로 찾는다(공백 무시; 안 되면 조각 찾기)."""
    off = d.off_of_line(head_line + 1)
    out, l_first, l_last, notes = [], None, None, []
    for cell in cells:
        if not ws(cell):
            out.append(cell)
            continue
        f = d.find(cell, off=off)
        if f and f[1] - head_line < 200:
            off = f[3]
            out.append(f[0])
            l_first = f[1] if l_first is None else min(l_first, f[1])
            l_last = f[2] if l_last is None else max(l_last, f[2])
            continue
        fp = d.find_pieces(cell, off)
        if fp:
            off = fp[3]
            out.append(fp[0])
            notes.append(f"칸 「{cell[:20]}…」 은 텍스트에서 {fp[4]}조각(사이에 쪽 넘김·다른 제목 줄이 끼어 있음 — 끼어든 줄은 뺌)")
            l_first = fp[1] if l_first is None else min(l_first, fp[1])
            l_last = fp[2] if l_last is None else max(l_last, fp[2])
            continue
        PROBLEMS.append(f"{co} {label} 칸 텍스트 대조 실패: {cell[:40]}")
        out.append(cell)
        notes.append(f"칸 「{cell[:20]}…」 은 텍스트 대조 실패 — 원문 XML 칸 글자를 실음")
    return out, l_first, l_last, notes


