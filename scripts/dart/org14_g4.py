HANG = r"가-힣A-Za-z0-9ㆍ·&"


def name_hit(unit, duty):
    """단위 이름이 담당업무 원문에 글자 그대로(공백까지 — 검증 g4 고침: 공백을 빼야만 맞는 것은 이름 일치가 아님) 있는지.
    경계는 원문(공백 포함)에서 본다: 앞은 글자가 아니거나 「겸」, 뒤는 글자가 아니거나 「장」·「소속」·「위원」."""
    u = (unit or "").strip()
    if not u or not duty:
        return False
    rx = r"\n?".join(re.escape(ch) for ch in u)   # 텍스트 파일 줄바꿈(PDF 줄 나눔)만 건너뜀 — 띄어쓰기는 그대로 맞춤
    for m in re.finditer(rx, duty):
        a, b = m.start(), m.end()
        left_ok = a == 0 or not re.match(f"[{HANG}]", duty[a - 1]) or duty[a - 1] == "겸"
        right_ok = b == len(duty) or not re.match(f"[{HANG}]", duty[b]) or duty[b:].startswith(("장", "소속", "위원"))
        if left_ok and right_ok:
            return True
    return False


