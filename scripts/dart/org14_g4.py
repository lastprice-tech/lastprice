def verb(d, cell, lo, span=60):
    """XML 칸 글을 텍스트 파일에서 공백 무시로 찾아 원문(줄바꿈 포함)으로. 못 찾으면 XML 칸 글 + 표시."""
    if not ws(cell):
        return cell, None
    f = d.find(cell, lo)
    if f and f[1] - lo <= span:
        return f[0], f
    return cell + " 〔XML 칸 글 — 텍스트 파일 대조 안 됨〕", None


def officers(co, docs):
    c = COS[co]
    tbls = xml_tables(c["biz"], c["sec_officer"], ["성명", "성별", "출생년월", "직위"])
    if len(tbls) != len(c["officer_kinds"]):
        PROBLEMS.append(f"{co} 임원 표 수 {len(tbls)} ≠ {len(c['officer_kinds'])}")
    d = docs["biz"]
    cur = d.line(c["officer_anchor"])
    out = []
    for kind, g in zip(c["officer_kinds"], tbls):
        for r in g:
            if ws(r[0]) == "성명" or len(r) < 7:
                continue
            f = d.find(r[0] + r[1] + r[2], cur)
            if not f:
                PROBLEMS.append(f"{co} 임원 {r[0]} 텍스트 위치 못 찾음")
                line = cur
                src = f"{d.label} · {d.ident} · 쪽 {NF}"
            else:
                line = f[1]
                cur = f[2]
                src = f"{d.label} · {d.ident} · {d.pages(f[1], f[2])} · {f[1] + 1}행"
            duty, fd = verb(d, r[6], line, 15)
            if fd:
                cur = max(cur, fd[2])
            out.append(dict(구분=kind, 성명=r[0], 성별=r[1], 출생년월=r[2], 직위=r[3], 등기=r[4], 상근=r[5], 담당업무=duty,
                            담당업무_xml=r[6], 재직기간=r[11] if len(r) > 11 else "", 임기만료일=r[12] if len(r) > 12 else "", 출처=src, line=line))
    return out


