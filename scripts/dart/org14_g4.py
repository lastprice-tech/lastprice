def out_fix(obj, co):
    """md·CSV 로 옮길 글에 OUT_FIX 를 건다(문자열·목록·튜플·사전을 따라 내려감). 쓰인 횟수를 회사별로 셈."""
    if isinstance(obj, str):
        for a, b in OUT_FIX:
            n = obj.count(a)
            if n:
                obj = obj.replace(a, b)
                FIX_USED[(co, a)] = FIX_USED.get((co, a), 0) + n
        return obj
    if isinstance(obj, tuple):
        return tuple(out_fix(x, co) for x in obj)
    if isinstance(obj, list):
        return [out_fix(x, co) for x in obj]
    if isinstance(obj, dict):
        return {k: out_fix(v, co) for k, v in obj.items()}
    return obj


