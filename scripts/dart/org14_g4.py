def build_quotes(co, docs):
    qs = {}
    for qid, dk, after, s, e, label in QUOTE_SPECS[co]:
        d = docs[dk]
        a0 = d.line(after) if after else 0
        l1 = d.line(s, a0)
        l2 = d.line(e, l1)
        if l2 - l1 > 90:
            PROBLEMS.append(f"{co} {qid} 인용이 너무 김({l2 - l1}줄)")
        lines = [l for i, l in enumerate(d.lines[l1:l2 + 1], l1) if not d.skip[i] or PAGE_RE.match(l.strip())]
        qs[qid] = dict(id=qid, doc=dk, l1=l1, l2=l2, label=label, lines=lines, src=d.src(l1, l2), short=d.short(l1, l2))
    return qs


def snip(docs, dk, after, text, near=None):
    """원문 조각을 공백 무시로 찾아 (원문, 쪽 출처, 첫 줄) — 못 찾으면 멈춤."""
    d = docs[dk]
    a0 = d.line(after) if after else 0
    f = d.find(text, a0)
    if not f:
        raise SystemExit(f"[{d.path}] 원문 조각 못 찾음: {text[:40]} (after {after})")
    return f[0], d.src(f[1], f[2]), f[1], f[2]


