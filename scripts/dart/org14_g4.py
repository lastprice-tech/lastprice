def mdc(s):
    return str(s if s is not None else "").replace("|", "\\|").replace("\n", " ⏎ ")


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for r in rows:
        out.append("| " + " | ".join(mdc(x) for x in r) + " |")
    return "\n".join(out)


