def to_kst(s):
    s = (s or "").strip()
    if not s:
        return ""
    s2 = re.sub(r"([+-]\d\d)(\d\d)$", r"\1:\2", s)
    try:
        d = datetime.datetime.fromisoformat(s2)
    except ValueError:
        return s
    if d.tzinfo is None:
        return s
    return d.astimezone(KST).strftime("%Y-%m-%d %H:%M KST")


# ───────────────────────── 텍스트 파일 ─────────────────────────
PAGE_RE = re.compile(r"^=== p\.(\d+) ===$")
FOOT_RE = re.compile(r"^전자공시시스템 dart\.fss\.or\.kr Page \d+$")


class TextDoc:
    """텍스트 파일 한 개. 줄(0부터)·쪽·공백 뺀 글자열(쪽 표지·DART 꼬리말 줄 제외)로 찾는다."""

    def __init__(self, path, label, ident, collected):
        self.path, self.label, self.ident, self.collected = path, label, ident, collected
        with open(P(path), encoding="utf-8") as f:
            self.lines = f.read().split("\n")
        self.page, self.skip = [], []
        S, pos = [], []
        p = 0
        for i, l in enumerate(self.lines):
            st = l.strip()
            m = PAGE_RE.match(st)
            if m:
                p = int(m.group(1))
            self.page.append(p)
            sk = bool(m) or bool(FOOT_RE.match(st))
            self.skip.append(sk)
            if sk:
                continue
            for j, ch in enumerate(l):
                if not ch.isspace():
                    S.append(ch)
                    pos.append((i, j))
        self.S = "".join(S)
        self.pos = pos
        self.foot = {}
        for i, l in enumerate(self.lines):
            m2 = re.match(r"^전자공시시스템 dart\.fss\.or\.kr Page (\d+)$", l.strip())
            if m2:
                self.foot.setdefault(self.page[i], m2.group(1))
        self.line_off = {}
        for k, (i, _) in enumerate(pos):
            self.line_off.setdefault(i, k)

    def off_of_line(self, i):
        while i < len(self.lines):
            if i in self.line_off:
                return self.line_off[i]
            i += 1
        return len(self.S)

    def line(self, rx, after=0, must=True):
        r = re.compile(rx)
        for i in range(after, len(self.lines)):
            if r.search(self.lines[i]):
                return i
        if must:
            raise SystemExit(f"[{self.path}] 줄을 못 찾음: {rx} (after {after})")
        return None

    def find(self, text, lo=0, hi=None):
        """공백 무시로 text 를 찾아 (원문 조각, 첫 줄, 끝 줄) 을 준다. 원문 조각은 텍스트 파일 글자 그대로(줄바꿈 포함)."""
        n = ws(text)
        if not n:
            return None
        k = self.S.find(n, self.off_of_line(lo))
        if k < 0:
            return None
        a, b = self.pos[k], self.pos[k + len(n) - 1]
        if hi is not None and a[0] > hi:
            return None
        parts = []
        for i in range(a[0], b[0] + 1):
            if self.skip[i]:
                continue
            l = self.lines[i]
            s = a[1] if i == a[0] else 0
            e = b[1] + 1 if i == b[0] else len(l)
            parts.append(l[s:e])
        return "\n".join(x.strip() for x in parts), a[0], b[0]

    def pages(self, l1, l2):
        p1, p2 = self.page[l1], self.page[l2]
        base = f"p.{p1}" if p1 == p2 else f"p.{p1}~{p2}"
        if p1 in self.foot:  # DART 뷰어 PDF 쪽 꼬리 「Page N」(인쇄 쪽 번호)도 함께
            f1, f2 = self.foot.get(p1), self.foot.get(p2, "?")
            base += f"(쪽 꼬리 Page {f1})" if p1 == p2 else f"(쪽 꼬리 Page {f1}~{f2})"
        return base

    def src(self, l1, l2):
        return f"[{self.label} · {self.ident} · {self.pages(l1, l2)} · 수집 {self.collected} · {self.path} {l1 + 1}~{l2 + 1}행]"

    def short(self, l1, l2):
        return f"{self.label} · {self.ident} · {self.pages(l1, l2)} · {l1 + 1}~{l2 + 1}행"


