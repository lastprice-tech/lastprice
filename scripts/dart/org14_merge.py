def main():
    check = "--check" in sys.argv[1:]
    outs = {}
    data = {}
    for kind, fname, head in KINDS:
        rows = merged_rows(kind, head)
        data[kind] = rows
        outs[os.path.join(HND, fname)] = csv_bytes(head, rows)
    wide_cos = {co for co in COS if len(read_csv(os.path.join(ORG, f"{co}_임원겸직.csv"))[0]) == 16}
    stats = {co: count_company(co, data["조직단위"], data["임원겸직"], wide_cos) for co in COS}
    md = build_md(data["조직단위"], data["임원겸직"], data["지원조직"], wide_cos, stats, meta())
    outs[os.path.join(HND, "00_목록.md")] = (md + "\n").encode("utf-8")
    bad = []
    for p, b in outs.items():
        old = open(p, "rb").read() if os.path.exists(p) else None
        if old == b:
            continue
        if check:
            bad.append(os.path.relpath(p, ROOT))
        else:
            with open(p, "wb") as f:
                f.write(b)
            print("썼음", os.path.relpath(p, ROOT), len(b), "bytes")
    if check:
        if bad:
            print("다시 만든 것과 다름:", ", ".join(bad))
            return 1
        print("합본 CSV 3개·00_목록.md 가 다시 만든 것과 같음")
        return 0
    for co in COS:
        s = stats[co]
        print(f"{SHORT[co]}: 단위 {len(s['main'])}(+보조 {len(s['aux'])}) · 직원인원 {len(s['staff'])} · 위원 {len(s['wiwon'])} · "
              f"임원 {len(s['execs'])}(등기 {len(s['reg'])}/미등기 {len(s['unreg'])}) · 겸직 {len(s['conc'])}(임원표 {len(s['conc_in'])}) · 표시 {len(s['marks'])}/{len(s['amarks'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
