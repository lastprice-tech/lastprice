def unit_rows(rows, co):
    rs = [x for x in rows if x[0] == co]
    main_doc = rs[0][1]
    return [x for x in rs if x[1] == main_doc], [x for x in rs if x[1] != main_doc]


def headcount_split(rs):
    """공시인원 칸에 값이 있는 행 → (직원 인원 단위, 위원·이사·구성원 수 단위)."""
    staff, wiwon = [], []
    for x in rs:
        v = x[8]
        if v.startswith("추출 범위에 없음") and not v.startswith("추출 범위에 없음(직원 인원)"):
            continue
        t = " ".join((x[8], x[9], x[11]))
        (wiwon if any(m in t for m in WIWON_MARKS) else staff).append(x[5])
    return staff, wiwon


def exec_table_2025(x, wide):
    """임원겸직 행이 2025.12.31 기준 임원 표 행인지. wide = g2~g4 꼴(16열) 회사."""
    if wide:
        return bool(re.search(r"임원\s?현황\(기준일 2025", x[13]))
    if x[2].startswith("임원 표("):
        return False
    return bool(re.search(r"임원 현황 \(기준일 : 2025년 12월 31일", x[12].split("‖")[0]))


def conc_table_2025(x, wide):
    """임원겸직 행이 2025.12.31 기준 계열회사 임원 겸직 표 행인지(겸직회사 칸에 회사 이름이 있는 행)."""
    if not x[8] or "나오지 않음" in x[8]:
        return False
    if wide:
        s = x[14]
        return "2025" in s and not any(k in s for k in CONC_EXCLUDE)
    s = x[12]
    if "‖ 겸직:" in s:
        part = s.split("‖ 겸직:", 1)[1]
    elif x[2].startswith("임원 표("):
        part = s
    else:
        return False
    return "2025년 12월 31일" in part


def count_company(co, units, execs, wide_cos):
    main, aux = unit_rows(units, co)
    st, wi = headcount_split(main)
    ast, awi = headcount_split(aux)
    marks = [(x[5], x[7]) for x in main if x[7].strip()]
    amarks = [(x[5], x[7]) for x in aux if x[7].strip()]
    er = [x for x in execs if x[0] == co]
    wide = co in wide_cos
    names = OrderedDict()
    for x in er:
        if exec_table_2025(x, wide):
            names.setdefault(x[1], x[3])
    reg = [n for n, g in names.items() if g in REG]
    unreg = [n for n, g in names.items() if g == "미등기"]
    other = [n for n, g in names.items() if g not in REG and g != "미등기"]
    conc = list(OrderedDict.fromkeys(x[1] for x in er if conc_table_2025(x, wide)))
    return {
        "main": main, "aux": aux, "staff": st, "wiwon": wi, "aux_staff": ast, "aux_wiwon": awi,
        "marks": marks, "amarks": amarks, "execs": list(names), "reg": reg, "unreg": unreg, "other": other,
        "conc": conc, "conc_in": [n for n in conc if n in names], "conc_out": [n for n in conc if n not in names],
    }


# ───────────── md 에서 읽는 값(직원 수) ─────────────
def md_section(co, num):
    L = open(os.path.join(HND, f"14_{co}.md"), encoding="utf-8").read().split("\n")
    s = next(i for i, l in enumerate(L) if l.startswith(f"## {num})"))
    e = next(i for i, l in enumerate(L) if i > s and l.startswith("## "))
    return L[s:e]


def staff_total(co):
    """md 2) 절의 직원 표 「합 계」 행에서 합계(다섯째 숫자 칸)를 읽는다. 여러 줄이면 모두 같아야 함."""
    vals = set()
    for l in md_section(co, 2):
        t = l.replace("`", " ").replace("|", " ").replace("*", " ").strip()
        t = t.lstrip("- ").strip()
        if not re.match(r"합\s?계\s", t):
            continue
        toks = [k for k in t.split() if k not in ("합", "계", "합계")]
        if len(toks) >= 5 and all(re.fullmatch(r"[\d,]+|-", k) for k in toks[:5]) and re.fullmatch(r"\d+", toks[4]):
            vals.add(int(toks[4]))
    if len(vals) != 1:
        raise SystemExit(f"{co} md 2) 「합 계」 행에서 합계를 하나로 읽지 못함: {vals}")
    return vals.pop()


