def read_csv(path):
    with open(path, encoding="utf-8-sig", newline="") as f:
        return list(csv.reader(f))


def map_header(src, head, kind):
    """회사 CSV 머리 → 합본 머리 자리 목록. 이름 꼴만 다른 열은 같은 자리로 본다."""
    out = []
    for i, h in enumerate(src):
        want = head[i] if i < len(head) else None
        if h == want:
            out.append(i)
            continue
        alias = HEADER_ALIAS.get(h)
        if kind == "조직단위" and i == 14 and h == "대응_방식":
            alias = head[14]
        if kind == "임원겸직" and i == 12 and h == "출처":
            alias = head[12]
        if alias != want:
            raise SystemExit(f"[{kind}] 열 {i} 「{h}」 를 합본 열 「{want}」 에 맞출 수 없음")
        out.append(i)
    return out


def merged_rows(kind, head):
    rows = []
    for co in COS:
        r = read_csv(os.path.join(ORG, f"{co}_{kind}.csv"))
        idx = map_header(r[0], head, kind)
        for x in r[1:]:
            if len(x) != len(r[0]):
                raise SystemExit(f"[{kind}] {co} 행 길이 {len(x)} ≠ 머리 {len(r[0])}")
            if x[0] != co:
                raise SystemExit(f"[{kind}] {co} 파일에 회사 칸 「{x[0]}」 행")
            row = [""] * len(head)
            for j, i in enumerate(idx):
                row[i] = x[j]
            rows.append(row)
    return rows


def csv_bytes(head, rows):
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\r\n")
    w.writerow(head)
    w.writerows(rows)
    return buf.getvalue().encode("utf-8-sig")


