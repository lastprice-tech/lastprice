def read_csv_dict(path):
    with open(path, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def table_labels(co, execs, wide):
    """임원겸직 CSV 에 들어 있는 임원 표·겸직 표 이름(회사 CSV 글 그대로)."""
    ex, cc = OrderedDict(), OrderedDict()
    for x in execs:
        if x[0] != co:
            continue
        if wide:
            if x[13]:
                ex[x[13]] = 1
            if x[14]:
                cc[x[14]] = 1
            continue
        a = x[12].split("‖")
        if not x[2].startswith("임원 표("):
            ex[re.sub(r"^.*?p\.\d+ · ", "", a[0]).strip()] = 1
        if len(a) > 1:
            cc[re.sub(r"\s*\(성명 칸은.*$", "", re.sub(r"^.*?p\.\d+ · ", "", a[1])).strip()] = 1
        elif x[2].startswith("임원 표("):
            cc[re.sub(r"\s*\(성명 칸은.*$", "", re.sub(r"^.*?p\.\d+ · ", "", a[0])).strip()] = 1
    return list(ex), list(cc)


