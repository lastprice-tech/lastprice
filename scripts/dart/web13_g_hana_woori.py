def read_csv(path):
    with open(path, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


PAGE_RE = re.compile(r"=== p\.(\d+) ===$")


class Text:
    """텍스트 파일 한 벌: 줄, 줄마다 쪽."""

    def __init__(self, doc_id):
        self.doc_id = doc_id
        self.path = os.path.join(TEXT, doc_id + ".txt")
        with open(self.path, encoding="utf-8") as f:
            self.lines = f.read().split("\n")
        self.page_of = []
        page = 0
        for ln in self.lines:
            m = PAGE_RE.match(ln.strip())
            if m:
                page = int(m.group(1))
            self.page_of.append(page)
        self.npages = max(self.page_of) if self.page_of else 0

    def pages_text(self):
        """쪽 번호 → 그 쪽 글(줄바꿈을 빼고 이어 붙임 — 줄 끝에서 끊긴 낱말도 잡히게)."""
        out = {}
        for ln, p in zip(self.lines, self.page_of):
            if PAGE_RE.match(ln.strip()):
                continue
            out.setdefault(p, []).append(ln.strip())
        return {p: "".join(v) for p, v in out.items()}


