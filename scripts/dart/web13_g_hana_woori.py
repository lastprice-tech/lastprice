_TEXTS = {}


def text(doc_id):
    if doc_id not in _TEXTS:
        _TEXTS[doc_id] = Text(doc_id)
    return _TEXTS[doc_id]


def locate(q):
    t = text(DOCS[(q["co"], q["doc"])]["doc_id"])
    L = t.lines
    i0 = None
    for i in range(max(0, q["from_"] - 1), len(L)):
        if (q["start"].startswith("=== p.") and L[i].strip() == q["start"]) or (not q["start"].startswith("=== p.") and q["start"] in L[i]):
            i0 = i
            break
    if i0 is None:
        raise SystemExit(f"[{q['id']}] 시작 글자열 못 찾음: {q['start']!r}")
    j0 = None
    for j in range(i0, len(L)):
        if q["end"] in L[j]:
            j0 = j + q["end_off"]
            break
    if j0 is None:
        raise SystemExit(f"[{q['id']}] 끝 글자열 못 찾음: {q['end']!r}")
    if j0 - i0 > 260:
        raise SystemExit(f"[{q['id']}] 범위가 너무 김: {i0 + 1}-{j0 + 1}")
    lines = L[i0:j0 + 1]
    while lines and not lines[-1].strip():
        lines.pop()
        j0 -= 1
    pages = sorted(set(t.page_of[i0:j0 + 1]))
    return dict(t=t, i0=i0, j0=j0, lines=lines, pages=pages)


def pages_label(pages):
    return f"p.{pages[0]}" if len(pages) == 1 else f"p.{pages[0]}–p.{pages[-1]}"


def norm(s):
    return re.sub(r"\s+", "", s)


def variant_check(q, loc):
    """정정·추가공시 판에 같은 글이 있는지(공백 무시). 다르면 다른 줄을 보여 줌."""
    out = []
    body = [ln for ln in loc["lines"] if not PAGE_RE.match(ln.strip())]
    nq = norm("".join(body))
    for vid in DOCS[(q["co"], q["doc"])]["variants"]:
        vt = text(vid)
        nv = norm("".join(ln for ln in vt.lines if not PAGE_RE.match(ln.strip())))
        if nq in nv:
            out.append((vid, "같음(공백 무시)", ""))
            continue
        miss = [ln.strip() for ln in body if len(norm(ln)) >= 6 and norm(ln) not in nv]
        if not miss:
            out.append((vid, "줄 단위로는 모두 있음(배치·이어짐이 다름 — 쪽 머리글·쪽 번호 줄 차이 포함)", ""))
            continue
        vlines = [ln.strip() for ln in vt.lines if ln.strip()]
        diffs = []
        for m in miss[:4]:
            best = difflib.get_close_matches(m, vlines, n=1, cutoff=0.6)
            diffs.append(f"본: {m} / 판: {best[0] if best else '(비슷한 줄 없음)'}")
        out.append((vid, f"다름 — 공백을 빼고도 없는 줄 {len(miss)}개", " ‖ ".join(diffs)))
    return out


