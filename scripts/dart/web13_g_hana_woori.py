ART_RE = re.compile(r"^\s*제\s*(\d+)\s*조(?:\s*의\s*(\d+))?\s*\(([^)]*)\)")


def toc_rows(co, qid, reg_name, doc_label, loc_label, full="Y(전문)"):
    """인용 블록에서 「제N조(제목)」 줄을 뽑는다. 부칙이 나오면 거기서 멈추고 「부칙」 한 줄만 단다(부칙 안의 제1조(시행일) 등은 조문 목차에 넣지 않음)."""
    q = next(x for x in QUOTES if x["id"] == qid)
    loc = locate(q)
    rows = []
    t = loc["t"]
    for k, ln in enumerate(loc["lines"]):
        p = t.page_of[loc["i0"] + k]
        if re.match(r"^\s*부\s*칙", ln):
            rows.append(dict(회사=CO_NAME[co], 규정명=reg_name, 조번호="부칙", 조제목="(시행일 — 부칙 전부)", 문서=doc_label,
                             접수번호또는URL=loc_label, 쪽=f"p.{p}", 전문여부=full))
            break
        m = ART_RE.match(ln)
        if m:
            no = f"제{m.group(1)}조" + (f"의{m.group(2)}" if m.group(2) else "")
            rows.append(dict(회사=CO_NAME[co], 규정명=reg_name, 조번호=no, 조제목=m.group(3).strip(), 문서=doc_label,
                             접수번호또는URL=loc_label, 쪽=f"p.{p}", 전문여부=full))
    return rows


