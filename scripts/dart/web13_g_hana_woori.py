def search_trail(co):
    rows = []
    for key in [(co, "연차"), (co, "사업"), (co, "경영공시")]:
        t = text(DOCS[key]["doc_id"])
        pt = t.pages_text()
        for lab, rx in SEARCH:
            r = re.compile(rx)
            hits = {p: len(r.findall(s)) for p, s in pt.items()}
            hits = {p: n for p, n in hits.items() if n}
            pl = sorted(hits)
            short = ", ".join(str(p) for p in pl[:30]) + (f" … (+{len(pl) - 30})" if len(pl) > 30 else "")
            rows.append((lab, key[1], f"p.1–p.{t.npages}", sum(hits.values()), len(pl), short, rx))
    return rows


def attach_pages(co):
    """첨부 N 의 첫 쪽: ATTACH_FROM 뒤에서 쪽 표지 다음 5줄 안에 『N. 이름』(공백 무시)이 처음 나오는 쪽."""
    t = text(DOCS[(co, "연차")]["doc_id"])
    res = {}
    last_marker = -99
    for i in range(ATTACH_FROM[co] - 1, len(t.lines)):
        ln = t.lines[i].strip()
        if PAGE_RE.match(ln):
            last_marker = i
            continue
        if i - last_marker > 5:
            continue
        for n, nm in ATTACH[co]:
            if n in res:
                continue
            if norm(ln) == norm(f"{n}. {nm}") or norm(ln) == norm(f"{n} . {nm}"):
                res[n] = t.page_of[i]
    missing = [n for n, _ in ATTACH[co] if n not in res]
    if missing:
        raise SystemExit(f"[{co}] 첨부 첫 쪽 못 찾음: {missing}")
    return res


