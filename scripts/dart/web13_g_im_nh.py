def toc_rows(spec, co, reg, note_fn=None):
    t = T(spec["doc"])
    d = DOCS[spec["doc"]]
    ref = d["rcp"] if d.get("rcp") else d["url"]
    rows = []
    for i in range(spec["s"], spec["e"] + 1):
        ln = t.lines[i]
        if BUCHIK_RE.match(ln):
            break
        m = CH_RE.match(ln)
        if m and len(ln.strip()) < 60:
            rows.append(dict(회사=co, 규정명=reg, 조번호=f"제{m.group(1)}장", 조제목=m.group(2), 문서=d["name"], 접수번호또는URL=ref,
                             쪽=t.plabel(t.page[i]), 전문여부="Y(전문 옮김)", 비고="장 제목"))
            continue
        m = ART_RE.match(ln)
        if m:
            no = f"제{m.group(1)}조" + (f"의{m.group(2)}" if m.group(2) else "")
            rows.append(dict(회사=co, 규정명=reg, 조번호=no, 조제목=m.group(3).strip(), 문서=d["name"], 접수번호또는URL=ref,
                             쪽=t.plabel(t.page[i]), 전문여부="Y(전문 옮김)", 비고=(note_fn(int(m.group(1))) if note_fn else "")))
    return rows


