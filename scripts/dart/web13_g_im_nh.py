def page_ranges(ps):
    ps = sorted(set(ps))
    out = []
    for p in ps:
        if out and p == out[-1][1] + 1:
            out[-1][1] = p
        else:
            out.append([p, p])
    return ", ".join(f"{a}" if a == b else f"{a}-{b}" for a, b in out)


def search_log(co_keys, quotes):
    rows = []
    for jo, pat, excl in SEARCH:
        rp = re.compile(pat)
        rx = re.compile(excl) if excl else None
        for k in co_keys:
            t = T(k)
            hit = [t.page[i] for i, ln in enumerate(t.lines) if rp.search(ln) and not (rx and rx.search(ln) and not rp.search(rx.sub("", ln)))]
            base = jo.split("(")[0]
            keys = base.split("·") if base[0].isdigit() else [base]
            used = sorted({p for qq in quotes if qq["doc"] == k and (base in qq["jo"] or any(j in qq["jo"] for j in keys)
                                                                     or ("4" in keys and "4·5" in qq["jo"]))
                           for p in qq["pages"]})
            rows.append(dict(조=jo, 검색어=pat + (f" (뺀 말: {excl})" if excl else ""), 문서=DOCS[k]["name"],
                             범위=f"p.1~{t.npages} 전체", 맞은줄=len(hit), 맞은쪽=page_ranges(hit) or "-", 옮긴쪽=page_ranges(used) or "-"))
    return rows


