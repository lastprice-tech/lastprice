def _skip(ln):
    """대조할 때 빼는 줄: 쪽 표지, 쪽 번호만 있는 줄, 쪽 머리말(인쇄 쪽 포함) — 추가공시·정정판은 쪽이 밀려 이 줄들만 다르다."""
    s = ln.strip()
    return bool(PAGE_RE.match(ln) or "dart.fss.or.kr Page" in ln or re.fullmatch(r"\d{1,3}", s)
                or re.fullmatch(r"- \d+ -", s) or IM_HEAD.match(s) or NH_HEAD.match(s))


def norm(s):
    s = "\n".join(ln for ln in s.split("\n") if not _skip(ln))
    return re.sub(r"\s+", "", s)


def norm_map(t):
    chars, pages = [], []
    for ln, p in zip(t.lines, t.page):
        if _skip(ln):
            continue
        c = re.sub(r"\s+", "", ln)
        chars.append(c)
        pages.extend([p] * len(c))
    return "".join(chars), pages


