    metas = {k: meta_for(k) for k in DOCS}
    if cmd == "check":
        for k, m in metas.items():
            print(k, m["표기"], m["위치"], "텍스트sha256", "OK" if m["텍스트sha256_확인"] else "MISMATCH", "수집", m.get("수집", ""))
