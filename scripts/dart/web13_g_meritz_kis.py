def cut(spec):
    t = T(spec["doc"])
    a, b = t.rng(spec["p1"], spec["p2"])
    s = None
    for i in range(a, b + 1):
        if spec["start"] in t.lines[i]:
            s = i
            break
    if s is None:
        raise SystemExit(f"[{spec['id']}] 시작 앵커 없음: {spec['start']!r} p.{spec['p1']}~{spec['p2']}")
    e = None
    n = 0
    for i in range(s, b + 1):
        if spec["end"] in t.lines[i] and (i > s or spec["end"] != spec["start"]):
            n += 1
            if n == spec["end_n"]:
                e = i
                break
    if e is None:
        raise SystemExit(f"[{spec['id']}] 끝 앵커 없음: {spec['end']!r} p.{spec['p1']}~{spec['p2']}")
    if spec["end_excl"]:
        e -= 1
    s -= spec["pre"]
    e += spec["post"]
    lines = t.lines[s:e + 1]
    while lines and not lines[-1].strip():
        lines.pop()
    pages = sorted({t.page[i] for i in range(s, e + 1) if not PAGE_RE.match(t.lines[i])})
    out = []
    for ln in lines:
        for anc, mark, where in spec["marks"]:
            if where == "before" and anc in ln and mark not in out:
                out.append(mark)
        out.append(ln)
        for anc, mark, where in spec["marks"]:
            if where == "after" and anc in ln and mark not in out:
                out.append(mark)
    for anc, mark, where in spec["marks"]:
        if mark not in out:
            raise SystemExit(f"[{spec['id']}] 표시 앵커 없음: {anc!r}")
    spec.update(lines=lines, out=out, s=s, e=e, pages=pages, plab=t.plabel(pages[0], pages[-1]))
    return spec


def corr_check(spec):
    """정정판·재공시판에 같은 글이 있는지(공백 무시) — 있으면 그 판의 쪽."""
    res = []
    body = norm("\n".join(spec["lines"]))
    head = body[:40]
    for ck in CORR.get(spec["doc"], []):
        ct = T(ck)
        if ck not in NMAP:
            NMAP[ck] = norm_map(ct)
        whole, pmap = NMAP[ck]
        lab = DOCS[ck].get("rcp") or "재공시"
        pos = whole.find(body)
        if pos >= 0:
            p1, p2 = pmap[pos], pmap[pos + len(body) - 1]
            res.append(f"{lab}: 같은 글 있음({ct.plabel(p1, p2)})")
            continue
        hp = whole.find(head)
        if hp >= 0:
            res.append(f"{lab}: 앞 40자는 {ct.plabel(pmap[hp])} 에 있으나 전체 글이 같지 않음")
        else:
            res.append(f"{lab}: 이 글 없음(그 판에 이 부분이 실려 있지 않음)")
    return res


