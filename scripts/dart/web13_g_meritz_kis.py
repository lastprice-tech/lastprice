ART_RE = re.compile(r"^\s*제\s?(\d+)\s?조\s?(?:의\s?(\d+)\s?)?\(([^)]*)\)")
CH_RE = re.compile(r"^\s*제\s?(\d+)\s?장\s*(\S.*?)\s*$")
BROKEN_ART = re.compile(r"^제 조 (.+?)(\d+) \(")


def toc_rows(spec, co, reg, broken=False):
    t = T(spec["doc"])
    d = DOCS[spec["doc"]]
    rows = []
    ref = d["rcp"] if d.get("rcp") else d["url"]
    for i in range(spec["s"], spec["e"] + 1):
        ln = t.lines[i]
        if re.match(r"^\s*부\s*칙\s*$", ln):
            break
        if broken:
            m = BROKEN_ART.match(ln)
            if m:
                rows.append(dict(회사=co, 규정명=reg, 조번호=f"제{m.group(2)}조", 조제목=m.group(1), 문서=d["name"],
                                 접수번호또는URL=ref, 쪽=t.plabel(t.page[i]), 전문여부="Y(전문 옮김 — 추출 깨짐 있음)",
                                 비고=f"원문 추출 표기 「{ln.strip()[:len(m.group(0))]}」 — 조 번호·제목은 깨진 자리를 읽어 붙임(판단)"))
            continue
        m = CH_RE.match(ln)
        if m and len(ln.strip()) < 30:
            rows.append(dict(회사=co, 규정명=reg, 조번호=f"제{m.group(1)}장", 조제목=m.group(2), 문서=d["name"],
                             접수번호또는URL=ref, 쪽=t.plabel(t.page[i]), 전문여부="Y(전문 옮김)", 비고="장 제목"))
            continue
        m = ART_RE.match(ln)
        if m:
            no = f"제{m.group(1)}조" + (f"의{m.group(2)}" if m.group(2) else "")
            rows.append(dict(회사=co, 규정명=reg, 조번호=no, 조제목=m.group(3).strip(), 문서=d["name"],
                             접수번호또는URL=ref, 쪽=t.plabel(t.page[i]), 전문여부="Y(전문 옮김)", 비고=""))
    return rows


