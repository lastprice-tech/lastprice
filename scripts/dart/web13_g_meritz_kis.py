def _skip(ln):
    """대조할 때 빼는 줄: 쪽 표지, 쪽 번호만 있는 줄(인쇄 쪽), DART 쪽 아래 머리말 — 재공시·정정판은 쪽이 밀려 이 줄들만 다르다."""
    s = ln.strip()
    return bool(PAGE_RE.match(ln) or "dart.fss.or.kr Page" in ln or re.fullmatch(r"\d{1,3}", s) or re.fullmatch(r"- \d+ -", s))


def norm(s):
    s = "\n".join(ln for ln in s.split("\n") if not _skip(ln))
    return re.sub(r"\s+", "", s)


def norm_map(t):
    """텍스트 전체를 공백 없이 이어 붙인 글과, 글자마다의 쪽 번호."""
    chars, pages = [], []
    for ln, p in zip(t.lines, t.page):
        if _skip(ln):
            continue
        c = re.sub(r"\s+", "", ln)
        chars.append(c)
        pages.extend([p] * len(c))
    return "".join(chars), pages


