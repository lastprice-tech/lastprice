def page_ranges(ps):
    ps = sorted(set(ps))
    out = []
    for p in ps:
        if out and p == out[-1][1] + 1:
            out[-1][1] = p
        else:
            out.append([p, p])
    return ", ".join(f"{a}" if a == b else f"{a}-{b}" for a, b in out)


