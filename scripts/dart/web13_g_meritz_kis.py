    def plabel(self, p1, p2=None):
        p2 = p2 or p1
        a = f"p.{p1}" if p1 == p2 else f"p.{p1}~{p2}"
        pr = [self.printed.get(p) for p in range(p1, p2 + 1) if self.printed.get(p)]
